-- PRODUCTS:
-- Public can read all published products.
-- Store team and owners can manage their rows.
CREATE POLICY "products_select_public"
  ON public.products FOR SELECT
  USING (true);

CREATE POLICY "products_insert_authorized"
  ON public.products FOR INSERT
  WITH CHECK (user_id = auth.uid() OR public.is_store_team());

CREATE POLICY "products_update_authorized"
  ON public.products FOR UPDATE
  USING (user_id = auth.uid() OR public.is_store_team())
  WITH CHECK (user_id = auth.uid() OR public.is_store_team());

CREATE POLICY "products_delete_authorized"
  ON public.products FOR DELETE
  USING (user_id = auth.uid() OR public.is_store_team());

-- ORDERS:
-- Buyers see their own orders; Store team sees all orders.
-- Updates are STRICTLY restricted to the store team / service-role server action.
-- Buyers CANNOT directly UPDATE orders via anon/authenticated key to forge status or total.
CREATE POLICY "orders_select_own_or_team"
  ON public.orders FOR SELECT
  USING (user_id = auth.uid() OR public.is_store_team());

CREATE POLICY "orders_insert_authenticated"
  ON public.orders FOR INSERT
  WITH CHECK (user_id = auth.uid() AND status = 'Pending');

CREATE POLICY "orders_update_store_team_only"
  ON public.orders FOR UPDATE
  USING (public.is_store_team())
  WITH CHECK (public.is_store_team());

-- PROMO CODES:
-- Public can read codes to validate them. Only store team manages codes.
CREATE POLICY "promo_codes_select_public"
  ON public.promo_codes FOR SELECT
