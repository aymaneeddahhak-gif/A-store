-- 1. EXTENSIONS
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- 2. PRODUCTS TABLE
CREATE TABLE IF NOT EXISTS public.products (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name           text NOT NULL,
  price          numeric NOT NULL CHECK (price >= 0),
  original_price numeric CHECK (original_price IS NULL OR original_price >= 0),
  description    text,
  category       text NOT NULL,
  badge          text,
  rating         numeric NOT NULL DEFAULT 0 CHECK (rating >= 0 AND rating <= 5),
  reviews        jsonb NOT NULL DEFAULT '[]'::jsonb,
  image          text NOT NULL,
  images         jsonb DEFAULT '[]'::jsonb,
  video          text,
  stock          integer NOT NULL DEFAULT 0 CHECK (stock >= 0),
  sold_count     integer NOT NULL DEFAULT 0 CHECK (sold_count >= 0),
  is_published   boolean NOT NULL DEFAULT true,
  featured       boolean NOT NULL DEFAULT false,
  likes          integer NOT NULL DEFAULT 0 CHECK (likes >= 0),
  user_id        uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  custom_colors  jsonb DEFAULT '[]'::jsonb,
  custom_sizes   jsonb DEFAULT '[]'::jsonb,
  created_at     timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS products_category_idx ON public.products (category);
CREATE INDEX IF NOT EXISTS products_featured_idx ON public.products (featured) WHERE featured = true;
CREATE INDEX IF NOT EXISTS products_user_idx     ON public.products (user_id);
CREATE INDEX IF NOT EXISTS products_published_idx ON public.products (is_published);

-- 3. ORDERS TABLE
CREATE TABLE IF NOT EXISTS public.orders (
  id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id           uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  items             jsonb NOT NULL,
  total             numeric NOT NULL CHECK (total >= 0),
  status            text NOT NULL DEFAULT 'Pending'
                    CHECK (status IN ('Pending','Confirmed','Processing','Shipped','Delivered','Cancelled')),
  promo_code        text,
  carrier           text,
  tracking_number   text,
  status_updated_at timestamptz,
  created_at        timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS orders_user_id_idx ON public.orders (user_id);
CREATE INDEX IF NOT EXISTS orders_status_idx  ON public.orders (status);
CREATE INDEX IF NOT EXISTS orders_created_idx ON public.orders (created_at DESC);

-- 4. PROMO CODES TABLE
CREATE TABLE IF NOT EXISTS public.promo_codes (
  code        text PRIMARY KEY,
  percent_off integer NOT NULL CHECK (percent_off > 0 AND percent_off <= 100),
  active      boolean NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now()
);

-- 5. DEALS POPUP TABLE (Single-row configuration)
CREATE TABLE IF NOT EXISTS public.deals_popup (
  id              integer PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  enabled         boolean NOT NULL DEFAULT true,
  title           text NOT NULL DEFAULT 'Discount',
  subtitle        text NOT NULL DEFAULT 'Up to',
  button_label    text NOT NULL DEFAULT 'Shop now',
  applied_percent smallint CHECK (applied_percent IS NULL OR (applied_percent > 0 AND applied_percent <= 100)),
  previous_prices jsonb,
  image_url       text,
  updated_at      timestamptz NOT NULL DEFAULT now()
);

-- 5b. CUSTOM CATEGORIES TABLE
CREATE TABLE IF NOT EXISTS public.categories (
  id         text PRIMARY KEY,
  label      text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- 5c. PRODUCT LIKES TABLE (Per-user wishlist deduplication)
CREATE TABLE IF NOT EXISTS public.product_likes (
  user_id    uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  product_id bigint NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, product_id)
);

INSERT INTO public.deals_popup (id, enabled, title, subtitle, button_label, applied_percent)
VALUES (1, true, 'Discount', 'Up to', 'Shop now', 50)
ON CONFLICT (id) DO NOTHING;

-- 6. STORE SETTINGS TABLE (Single-row configuration)
CREATE TABLE IF NOT EXISTS public.store_settings (
  id                 integer PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  store_name         text NOT NULL DEFAULT 'A-store',
  currency           text NOT NULL DEFAULT 'USD' CHECK (currency IN ('USD', 'EUR', 'GBP')),
  notification_email text NOT NULL DEFAULT '',
  updated_at         timestamptz NOT NULL DEFAULT now()
);

INSERT INTO public.store_settings (id, store_name, currency)
VALUES (1, 'A-store', 'USD')
ON CONFLICT (id) DO NOTHING;

-- 7. NEWSLETTER SUBSCRIBERS TABLE
CREATE TABLE IF NOT EXISTS public.newsletter_subscribers (
  email      text PRIMARY KEY CHECK (email ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
  source     text NOT NULL DEFAULT 'footer',
  created_at timestamptz NOT NULL DEFAULT now()
);

-- 8. AUDIT LOG TABLE
CREATE TABLE IF NOT EXISTS public.audit_log (
  id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  actor_id    uuid,
  actor_email text,
  action      text NOT NULL,
  entity      text NOT NULL,
  entity_id   text,
  detail      jsonb,
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS audit_log_created_idx ON public.audit_log (created_at DESC);
CREATE INDEX IF NOT EXISTS audit_log_entity_idx  ON public.audit_log (entity, entity_id);

-- ============================================================================
-- HELPER FUNCTIONS & RLS POLICIES
-- ============================================================================

-- Store team check based on authenticated session email
CREATE OR REPLACE FUNCTION public.is_store_team()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
AS $$
  SELECT lower(coalesce(auth.jwt() ->> 'email', '')) IN (
    'admin@a-store.shop',
    'tester@a-store.shop'
  );
$$;

